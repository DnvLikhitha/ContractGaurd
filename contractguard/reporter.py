"""Reporter: outputs findings as Rich terminal tables or clean JSON, and generates verification receipts."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Sequence

from rich import box
from rich.console import Console
from rich.table import Table

from contractguard.models import Finding, VerificationResult

_console = Console(stderr=True)

# Severity styles and badges for Rich output
_SEVERITY_STYLE = {
    "critical": "bold red",
    "high": "red",
    "medium": "yellow",
    "low": "cyan",
    "info": "dim white",
}

_SEVERITY_BADGE = {
    "critical": "[CRITICAL]",
    "high": "[HIGH]    ",
    "medium": "[MEDIUM]  ",
    "low": "[LOW]     ",
    "info": "[INFO]    ",
}

_STATUS_BADGE = {
    "VERIFIED": "[green]VERIFIED[/green]",
    "ROLLED_BACK": "[red]ROLLED_BACK[/red]",
    "SKIPPED": "[yellow]SKIPPED[/yellow]",
}


# ---------------------------------------------------------------------------
# JSON output
# ---------------------------------------------------------------------------

def findings_to_json(findings: Sequence[Finding]) -> str:
    """Serialise a list of Finding objects to a formatted JSON string.

    Uses Pydantic's model_dump so enums are serialised to their string values.
    """
    data = [f.model_dump(mode="json") for f in findings]
    return json.dumps(data, indent=2)


# ---------------------------------------------------------------------------
# Rich terminal table output
# ---------------------------------------------------------------------------

def print_findings_table(findings: Sequence[Finding]) -> None:
    """Print findings as a Rich table to stderr.

    Table columns: #, Severity, Category, File:Line, Title, Conf.
    Outputs a summary counts line before the table.
    """
    if not findings:
        _console.print("[green]✔ No findings detected.[/green]")
        return

    counts: dict[str, int] = {}
    for f in findings:
        counts[f.severity] = counts.get(f.severity, 0) + 1

    summary_parts = []
    for sev in ("critical", "high", "medium", "low", "info"):
        n = counts.get(sev, 0)
        if n:
            style = _SEVERITY_STYLE[sev]
            summary_parts.append(f"[{style}]{n} {sev.upper()}[/{style}]")
    _console.print(f"[bold]Findings:[/bold] " + "  ".join(summary_parts))

    table = Table(
        box=box.ROUNDED,
        show_lines=True,
        header_style="bold white",
        expand=False,
    )
    table.add_column("#",         style="dim", width=4)
    table.add_column("Severity",  width=14)
    table.add_column("Category",  width=10)
    table.add_column("File:Line", style="cyan", width=30)
    table.add_column("Title",     style="bold", min_width=24)
    table.add_column("Conf.",     width=6)

    for idx, finding in enumerate(findings, start=1):
        sev = finding.severity
        style = _SEVERITY_STYLE.get(sev, "")
        badge = _SEVERITY_BADGE.get(sev, sev.upper())
        location = finding.file
        if finding.line is not None:
            location += f":{finding.line}"

        table.add_row(
            str(idx),
            f"[{style}]{badge}[/{style}]",
            finding.category,
            location,
            finding.title,
            f"{finding.confidence:.2f}",
        )

    _console.print(table)


# ---------------------------------------------------------------------------
# Verification receipt
# ---------------------------------------------------------------------------

def write_verification_receipt(
    results: Sequence[VerificationResult],
    output_path: Path,
) -> None:
    """Write a VERIFICATION_RECEIPT.md file summarising patch outcomes.

    Includes:
      - Finding ID
      - Status (VERIFIED or ROLLED_BACK)
      - Verifier command
      - Verification strength (TESTS_PASSED, SYNTAX_ONLY, NO_VERIFIER)
      - Verifier output summary
    """
    lines: list[str] = [
        "# VERIFICATION_RECEIPT.md\n\n",
        "_Generated by ContractGuard `heal` command._\n\n",
        "| # | Finding ID | File | Status | Strength | Verifier Command | Output Summary |\n",
        "|---|-----------|------|--------|----------|------------------|----------------|\n",
    ]

    for idx, r in enumerate(results, start=1):
        status_val = getattr(r.status, "value", str(r.status))
        status_badge = _STATUS_BADGE.get(status_val, status_val)
        strength_val = getattr(r.strength, "value", str(r.strength))

        # Format clean 1-line output summary
        clean_out = " ".join((r.output or "No output").split())
        if len(clean_out) > 50:
            clean_out = clean_out[:47] + "..."
        clean_out = clean_out.replace("|", "/")

        lines.append(
            f"| {idx} | `{r.finding_id}` | `{r.patch.file}` "
            f"| {status_badge} | `{strength_val}` | `{r.verifier_used}` | {clean_out} |\n"
        )

    if not results:
        lines.append("| — | — | — | No patches applied | — | — | — |\n")

    lines.append("\n## Verification Details\n\n")
    for idx, r in enumerate(results, start=1):
        status_val = getattr(r.status, "value", str(r.status))
        strength_val = getattr(r.strength, "value", str(r.strength))
        lines.append(f"### {idx}. `{r.finding_id}` — {status_val}\n\n")
        lines.append(f"- **Finding ID:** `{r.finding_id}`\n")
        lines.append(f"- **File:** `{r.patch.file}`\n")
        lines.append(f"- **Patch Description:** {r.patch.description}\n")
        lines.append(f"- **Status:** **{status_val}**\n")
        lines.append(f"- **Verification Strength:** `{strength_val}`\n")
        lines.append(f"- **Verifier Command:** `{r.verifier_used}`\n")
        lines.append(f"- **Baseline Passed:** {r.baseline_passed}\n")
        lines.append(f"- **Patch Passed:** {r.patch_passed}\n")
        if r.error:
            lines.append(f"- **Error:** {r.error}\n")
        lines.append(f"- **Output Summary:**\n```\n{r.output.strip() if r.output else 'No output'}\n```\n\n")

    output_path.write_text("".join(lines), encoding="utf-8")
