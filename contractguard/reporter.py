"""
contractguard.reporter
======================
Responsible for all human-readable and machine-readable output.

Public API
----------
findings_to_json(findings)        -> str (JSON array)
print_findings_table(findings)    -> None (Rich table to stdout)
write_verification_receipt(results, path) -> None (writes .md file)
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Sequence

from rich.console import Console
from rich.table import Table
from rich import box

from contractguard.models import Finding, VerificationResult

# Colour map for severity levels
_SEVERITY_STYLE: dict[str, str] = {
    "critical": "bold red",
    "high":     "red",
    "medium":   "yellow",
    "low":      "cyan",
    "info":     "dim",
}

# Emoji/badge for severity
_SEVERITY_BADGE: dict[str, str] = {
    "critical": "🔴 CRITICAL",
    "high":     "🟠 HIGH",
    "medium":   "🟡 MEDIUM",
    "low":      "🔵 LOW",
    "info":     "⚪ INFO",
}

# Badge for fix status
_STATUS_BADGE: dict[str, str] = {
    "VERIFIED":     "✅ VERIFIED",
    "ROLLED_BACK":  "❌ ROLLED_BACK",
    "SKIPPED":      "⏭  SKIPPED",
}

_console = Console()


# ---------------------------------------------------------------------------
# JSON output
# ---------------------------------------------------------------------------

def findings_to_json(findings: Sequence[Finding]) -> str:
    """Serialise a sequence of Finding objects to a JSON array string."""
    return json.dumps(
        [f.model_dump() for f in findings],
        indent=2,
        default=str,
    )


# ---------------------------------------------------------------------------
# Rich table output
# ---------------------------------------------------------------------------

def print_findings_table(findings: Sequence[Finding]) -> None:
    """Print a colour-coded Rich table of findings to the terminal."""
    if not findings:
        _console.print("[bold green]✓ No findings.[/bold green]")
        return

    # Summary header
    counts: dict[str, int] = {}
    for f in findings:
        counts[f.severity] = counts.get(f.severity, 0) + 1

    summary_parts = []
    for sev in ("critical", "high", "medium", "low", "info"):
        n = counts.get(sev, 0)
        if n:
            style = _SEVERITY_STYLE[sev]
            summary_parts.append(f"[{style}]{n} {sev.upper()}[/{style}]")
    _console.print(f"[bold]Findings:[/bold] " + "  ".join(summary_parts))

    table = Table(
        box=box.ROUNDED,
        show_lines=True,
        header_style="bold white",
        expand=False,
    )
    table.add_column("#",         style="dim", width=4)
    table.add_column("Severity",  width=14)
    table.add_column("Category",  width=10)
    table.add_column("File:Line", style="cyan", width=30)
    table.add_column("Title",     style="bold", min_width=24)
    table.add_column("Conf.",     width=6)

    for idx, finding in enumerate(findings, start=1):
        sev = finding.severity
        style = _SEVERITY_STYLE.get(sev, "")
        badge = _SEVERITY_BADGE.get(sev, sev.upper())
        location = finding.file
        if finding.line is not None:
            location += f":{finding.line}"

        table.add_row(
            str(idx),
            f"[{style}]{badge}[/{style}]",
            finding.category,
            location,
            finding.title,
            f"{finding.confidence:.2f}",
        )

    _console.print(table)


# ---------------------------------------------------------------------------
# Verification receipt
# ---------------------------------------------------------------------------

def write_verification_receipt(
    results: Sequence[VerificationResult],
    output_path: Path,
) -> None:
    """Write a VERIFICATION_RECEIPT.md file summarising patch outcomes."""
    lines: list[str] = [
        "# VERIFICATION_RECEIPT.md\n",
        "_Generated by ContractGuard `heal` command._\n\n",
        f"| # | Finding ID | File | Status | Strength | Verifier |\n",
        f"|---|-----------|------|--------|----------|----------|\n",
    ]

    for idx, r in enumerate(results, start=1):
        status_badge = _STATUS_BADGE.get(r.status, r.status)
        lines.append(
            f"| {idx} | `{r.finding_id}` | `{r.patch.file}` "
            f"| {status_badge} | {r.strength} | {r.verifier_used} |\n"
        )

    if not results:
        lines.append("| — | — | — | No patches applied | — | — |\n")

    lines.append("\n## Detail\n\n")
    for idx, r in enumerate(results, start=1):
        lines.append(f"### {idx}. `{r.finding_id}` — {r.status}\n\n")
        lines.append(f"- **File:** `{r.patch.file}`\n")
        lines.append(f"- **Status:** {r.status}\n")
        lines.append(f"- **Verification strength:** `{r.strength}`\n")
        lines.append(f"- **Verifier used:** `{r.verifier_used}`\n")
        lines.append(f"- **Baseline passed:** {r.baseline_passed}\n")
        lines.append(f"- **Patch passed:** {r.patch_passed}\n")
        if r.error:
            lines.append(f"- **Error:** {r.error}\n")
        lines.append("\n")

    output_path.write_text("".join(lines), encoding="utf-8")
